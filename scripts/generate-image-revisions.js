const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const contentPath = path.join(__dirname, '../src/config/content.js');
const imgDir = path.join(__dirname, '../public/img');
const outputPath = path.join(__dirname, '../src/config/imageRevisions.js');

const content = fs.readFileSync(contentPath, 'utf8');
const animalSection = content.match(/const animalItems = \[([\s\S]*?)\];/);

if (!animalSection) {
  console.error('Could not parse animalItems from content.js');
  process.exit(1);
}

const filenames = [...animalSection[1].matchAll(/value:\s*'([^']+)'/g)].map(
  (match) => match[1]
);

const imageRevisions = {};

for (const filename of filenames) {
  const filePath = path.join(imgDir, filename);
  if (!fs.existsSync(filePath)) {
    console.warn(`Warning: missing image file ${filename}`);
    continue;
  }
  const hash = crypto
    .createHash('md5')
    .update(fs.readFileSync(filePath))
    .digest('hex');
  imageRevisions[`/img/${filename}`] = hash;
}

const output = `// Auto-generated by scripts/generate-image-revisions.js — do not edit manually
export const imageRevisions = ${JSON.stringify(imageRevisions, null, 2)};
`;

fs.writeFileSync(outputPath, output);
console.log(`Generated ${outputPath} with ${Object.keys(imageRevisions).length} entries`);
